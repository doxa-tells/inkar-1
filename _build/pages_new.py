def build_registry_json():
    data = []
    for i, r in enumerate(REG, 1):
        n = str(i).zfill(2)
        r = dict(r)
        r["slotPhoto"] = "REG-P" + n
        r["slotDraw"] = "REG-D" + n
        r["photoDesc"] = PHOTO_D.format(t=r["title"])
        r["drawDesc"] = DRAW_D.format(t=r["title"])
        data.append(r)
        for slot, d in ((r["slotPhoto"], r["photoDesc"]), (r["slotDraw"], r["drawDesc"])):
            MEDIA.append(dict(slot=slot, page="reestr.html", page_title="Реестр изделий",
                              ratio="4:3", kind="image", desc=d, src="",
                              prompt=d.strip() + " " + STYLE_TAIL))
    os.makedirs(os.path.join(OUT, "assets"), exist_ok=True)
    with open(os.path.join(OUT, "assets", "registry.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    return len(data)


